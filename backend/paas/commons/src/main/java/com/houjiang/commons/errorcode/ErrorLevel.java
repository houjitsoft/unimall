package com.houjiang.commons.errorcode;

/**
 * 错误级别：决定告警优先级与排障响应时效。
 *
 * <p>解决的问题：旧枚举没有级别概念，「手机号已存在」和「数据库不可达」在监控里是同一种事件，
 * 运维无法按严重度聚合告警（PRD 痛点 5）。
 *
 * <p>判定口径（PRD §5.1）：
 * <ul>
 *   <li>{@link #INFO} —— 用户操作可自行纠正（参数填错、查不到数据），不需要告警。</li>
 *   <li>{@link #WARN} —— 业务规则阻断但系统健康（库存不足、重复提交、权限不足），只做统计。</li>
 *   <li>{@link #ERROR} —— 单请求失败，系统整体仍可用（未知的运行时异常），需关注趋势。</li>
 *   <li>{@link #FATAL} —— 依赖故障或数据异常，需人工介入（DB 不可达、上游 5xx、资金类异常），必须告警。</li>
 * </ul>
 *
 * @author Amos
 * @since v1.2.0
 */
public enum ErrorLevel {

    /** 用户可自行纠正，不告警。 */
    INFO,

    /** 业务规则阻断，系统健康，仅统计。 */
    WARN,

    /** 单请求失败，系统仍可用，关注趋势。 */
    ERROR,

    /** 依赖故障 / 数据异常，需人工介入，必须告警（自检 V9 要求必填排查指引）。 */
    FATAL
}
