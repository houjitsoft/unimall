function rowsToMap(rows, locale) {
  const column = LOCALE_COLUMN[locale] ?? LOCALE_COLUMN['zh-CN']
  return Object.fromEntries(rows.map(row => [row[0], row[column]]))
}

export function createMenuMessages(locale) {
  const groups = rowsToMap(GROUP_ROWS, locale)
  return {
    groups,
    paths: rowsToMap(PATH_ROWS, locale),
    permissions: Object.fromEntries(
      Object.entries(groups).map(([index, title]) => [`geo:group:${index}`, title])
    )
  }
}
